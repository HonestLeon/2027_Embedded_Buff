/**
 * @file config_buff.h
 * @brief 能量机关游戏规则的时序与开关 —— 老逻辑原值
 *
 * 本文件主从共用(与主机同名文件保持一致), 但**从机只用其中一部分**:
 *   【主从共用】BUFF_PANEL_NUM —— 灯板数, 决定板号合法范围(见 SLAVE_PANEL_NUM 的 #error);
 *   【仅主机用】下面所有 BIG/HIT/WINDOW/GAP/RANDOM/SMALL_HIT/FIRST_HIT/P4 项 ——
 *                从机不跑大小符状态机(它只被动响应点亮/熄灭/复位/全亮), 换成从机状态机后
 *                这些宏在从机构建里不再被引用(S5 之后可整段搬走, 先留着便于与主机 diff)。
 * 从机侧新增常量(击打消抖、上报节流等)在 S4/S5 落地时再加在这里, 并标【仅从机用】。
 */
#ifndef CONFIG_BUFF_H
#define CONFIG_BUFF_H

#define BUFF_PANEL_NUM           5     /* 【主从共用】灯板数(板号 1~5)          */
#define BUFF_BIG_ROUNDS          5     /* 【仅主机】大符激活双灯板次数(=规则"5 组灯臂") */
#define BUFF_HIT_TIMEOUT_MS      2500u /* 【仅主机】无击打超时复位(老reset_t>=2.5) */
#define BUFF_HIT_WINDOW_MS       1000u /* 【仅主机】大符首击后窗口(老first_hit_flag+wait_t) */
#define BUFF_EXTINGUISH_GAP_MS   150u  /* 【仅主机】熄灭旧对 → 点亮新对的间隔(大符轮次切换)
 *
 * 规则约束(官方): "重新随机点亮下一组装甲模块前, 灯臂和装甲模块灯效将熄灭至多 200ms"
 *   → 上限 200ms; 取 150ms 留裕量, 同时让"旧对熄灭→新对点亮"肉眼可见。
 *
 * ⚠ 为什么不能取 1ms(老代码) 或 5ms:
 *   该间隔内主机要发两帧(先 0x01 熄灭旧对, 再 0x02 点亮新对), 从机必须**两帧都收到**
 *   才能把旧对熄掉。老从机是"单缓冲 + 200ms 主循环", 1ms 的两帧只会看到后一帧
 *   → 熄灭帧被吞 → 旧对不熄(这正是 2025 老固件实际表现为"不熄灭"的原因)。
 *   ⇒ 从机必须及时处理 CAN(建议 1ms 排空队列, 见从机模板 README 的"协议时序要求")。
 *   若用 200ms 单缓冲的从机与之对接, 熄灭仍会丢失(旧从机固有缺陷, 新从机已修复)。 */
#define BUFF_RANDOM_ARRAY_LEN    5     /* 【仅主机】随机序列长度 */

/* ── 【主从共用常量, 仅主机随机用到】大符可用组合数 = C(BUFF_PANEL_NUM, 2) ──
 * buff_random_big() 从这 C 种"两块组合"里**无重复**抽 BUFF_RANDOM_ARRAY_LEN 组,
 * 保证 5 轮不会出现同一对点两遍(函数注释见与主机逐字节一致的 buff.c)。 */
#define BUFF_BIG_PAIR_NUM        (BUFF_PANEL_NUM * (BUFF_PANEL_NUM - 1) / 2)

#if BUFF_RANDOM_ARRAY_LEN > BUFF_BIG_PAIR_NUM
#error "大符轮数超过可用两两组合数 C(BUFF_PANEL_NUM,2), buff_random_big 无法保证各组互不相同"
#endif

/* ── 【仅主机】小符需要击中的次数 ──
 * 5 = 按规则(5 个灯板各一次)              ← 新实现默认
 * 6 = 复刻 2025 老固件的实际行为: 老代码 `num[counter]` 在 counter==5 时越界读
 *     (读到相邻数组 num2[0]), 导致实际会多点亮/多击打一次(重复点亮一个已打过的灯板)。
 * 置 6 时, 第 6 次会显式重新点亮 s_small[0](把越界读变成有定义的行为)。
 * ⚠ 改动会影响比赛规则判定, 上赛场前与队伍确认用哪个值。 */
#define BUFF_SMALL_HIT_COUNT     5u

/* ── 【仅主机】第一组(刚点亮的第一块/第一对)是否也受 2.5s 超时约束 ──
 * 0 = **第一块/第一组不计时**(无限等待第一次击中)   ← 当前设置(队伍确定)
 * 1 = 任何被点亮的装甲模块都受 2.5s 约束
 * 备注: 规则 5.5.2.1 的字面表述把"未能在 2.5 秒内击中点亮的装甲模块"列为激活失败条件
 *       (含第一块); 实际按 0 执行(与 2025 老固件一致), 如赛前裁判有异议再切 1。 */
#define BUFF_FIRST_HIT_TIMEOUT_EN 0u

/* ── 【仅主机】P4 联调临时开关 ──
 * 1 = buff_step() 每 4Hz 发一帧 0x161(全复位) 并把 CAN1 收到的从机帧排空计数,
 *     用于 CAN 盒/从机联调验证收发链路(看 g_dbg_can1_rx_frames);
 * 0 = 关闭(P6 实现大小符状态机后置 0)。 */
#define BUFF_P4_CAN_TEST         0

/* 【仅从机】大符"点亮帧隐含熄灭"(差异表 #21) —— 1=启用, 0=关闭(回到老 Decode 语义)
 *   启用: 大符下收到 0x02 点亮帧而本板不在 [3]/[5] 里 → 按熄灭处理
 *         → 熄灭帧丢失时残留板在下一轮自愈(消除"3 块板同时亮")
 *   关闭: 只有"板号命中"才动作, 不在本轮的板保持原状态(老行为)
 *   ⚠ 排查用开关: 若怀疑"某块板该亮却一直不亮", 置 0 重编译做 A/B ——
 *     关闭后现象消失 = 隐式熄灭把它误灭了; 仍在 = 与本项无关(查 hit_detect/板号/主机)。 */
#define SLV_IMPLICIT_OFF_EN      1

/* ── 【仅从机】击打判定(S4, 《从机重构清单》§3.4 硬约束①③ / 差异表 #19) ──
 * 窗内一律吞(同引脚回弹与相邻电极抖动都是杂散沿), 超窗**任何引脚**都算打错候选
 * (2026-10-10 验收修正: 打错不再要求"引脚≠上次击发引脚" —— 那会永久吞掉同一环的
 *  再击打, 台架⑩"已激活板再打同一环"将无上报; 引脚仍记入 g_dbg_hit.last_pin 供观测)。
 * 老代码靠 start 全局锁存 ≈400ms: 100~400ms 区间的"第二环真击"老被吞、新会判打错 ——
 * 有意收紧, 台架 ⑨/⑩ 留意; 若赛场出现误复位, 把本值加大即回到老的保护强度。
 * 取 100ms = 2× 机械抖动上限 + 余量; HIT 事件待消费期间(≤250ms)新打错暂存 ev_lost,
 * 实际保护 ≈100+250ms。 */
#define HD_IGNORE_MS             100u

#endif /* CONFIG_BUFF_H */
